/**
 * Exports the SYNTHETIC seeded database to demo/public/data.json for the static GitHub Pages demo.
 * Refuses to run unless the data came from the synthetic mirror (every project has an example.invalid url
 * in the fixture), so real research data can never be exported by accident.
 *   pnpm demo:data
 */
import "dotenv/config";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { PrismaClient } from "../src/generated/prisma/client";
import { PrismaPg } from "@prisma/adapter-pg";

const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL! }) });

function assertSynthetic() {
  const readme = "fixtures/mirror/README.md";
  if (!existsSync(readme) || !readFileSync(readme, "utf8").includes("Synthetic mirror")) throw new Error("fixtures/mirror is not the synthetic mirror; refusing to export");
}

async function main() {
  assertSynthetic();
  const projects = await db.project.findMany({ select: { id: true, name: true, productArea: true, startDate: true, externalId: true, access: true } });
  // Only projects that came from the synthetic fixture (they carry fixture external ids) and are OPEN.
  const fixtureIds = new Set<string>();
  for (const p of projects) if (p.externalId) fixtureIds.add(p.id);
  if (fixtureIds.size !== projects.length) throw new Error("Found projects without a fixture external id; refusing to export");
  const open = projects.filter((p) => p.access === "OPEN");
  const openIds = open.map((p) => p.id);

  const sources = await db.source.findMany({ where: { projectId: { in: openIds } }, select: { id: true, projectId: true, title: true, date: true, kind: true, participants: { select: { participantId: true, speakerLabel: true } } } });
  const sourceIds = sources.map((s) => s.id);
  const segments = await db.segment.findMany({ where: { sourceId: { in: sourceIds } }, orderBy: [{ sourceId: "asc" }, { order: "asc" }], select: { id: true, sourceId: true, order: true, speaker: true, startMs: true, text: true } });
  const highlights = await db.highlight.findMany({ where: { sourceId: { in: sourceIds }, status: "ACTIVE" }, select: { id: true, sourceId: true, startSegmentId: true, startOffset: true, endSegmentId: true, endOffset: true, text: true, createdAt: true, tags: { select: { tagId: true } } } });
  const tags = await db.tag.findMany({ where: { archivedAt: null }, select: { id: true, name: true, color: true, groupId: true } });
  const groups = await db.tagGroup.findMany({ orderBy: { position: "asc" }, select: { id: true, name: true, color: true } });
  const participants = await db.participant.findMany({ select: { id: true, name: true, role: true, company: true, segment: true, toolsUsed: true } });

  // Demo themes: findings built from keyword matches, so the Themes pivot has something to show.
  const pick = (re: RegExp) => highlights.filter((h) => re.test(h.text)).map((h) => h.id);
  const themes = [
    { id: "theme-spreadsheets", title: "Spreadsheets are the real component library", description: "Engineers keep their own qualified-parts spreadsheets and treat the vendor catalogue as a second step.", confidence: "HIGH", productArea: null, parentId: null, highlightIds: pick(/spreadsheet|workbook/i) },
    { id: "theme-datasheets", title: "Data sheets break at the one missing parameter", description: "Trust in data sheets is high until a needed value is absent, which sends people to distributors or support.", confidence: "MEDIUM", productArea: null, parentId: null, highlightIds: pick(/data sheet|datasheet/i) },
    { id: "theme-support", title: "Support speed decides vendor loyalty", description: "A same-day FAE answer keeps the design on the vendor's parts; a slow one loses it.", confidence: "MEDIUM", productArea: null, parentId: null, highlightIds: pick(/FAE|support/i) },
    { id: "theme-simulation", title: "Simulation is where the workflow breaks", description: "Hand-transcribing values between tools is the recurring failure point.", confidence: "LOW", productArea: null, parentId: "theme-spreadsheets", highlightIds: pick(/simulat/i) },
  ];

  mkdirSync("demo/public", { recursive: true });
  const out = { generatedAt: new Date().toISOString(), note: "Synthetic data generated by scripts/generate-synthetic-mirror.ts. No real research.", projects: open.map(({ externalId, access, ...p }) => { void externalId; void access; return p; }), sources, segments, highlights, tags, groups, participants, themes };
  writeFileSync("demo/public/data.json", JSON.stringify(out));
  console.log(`exported ${open.length} projects, ${sources.length} sources, ${segments.length} segments, ${highlights.length} highlights, ${tags.length} tags, ${themes.length} themes → demo/public/data.json (${Math.round(JSON.stringify(out).length / 1024)} KB)`);
}

main().catch((e) => { console.error(e); process.exit(1); }).finally(() => db.$disconnect());
